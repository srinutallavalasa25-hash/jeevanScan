import type { IncidentRecord, IncidentPriority } from '../../types/database';
import type {
  IncidentReviewReport,
  ExtractedHazard,
  UrgencyRationaleRule,
  ImageDecisionSupport,
} from '../../types/phase11';
import { isValidCoordinate, hasValidCoordinates } from '../map/mapUtils';

export const MANDATORY_SAFETY_DISCLAIMER =
  'DECISION SUPPORT ONLY: This assessment is generated by an automated decision-support rule engine to assist human triage. It is NOT a medical diagnosis, does NOT determine survivability, and does NOT dispatch emergency responders. In life-threatening emergencies, immediately contact local emergency services (112 / 100 / 108).';

/**
 * Keyword hazard mapping dictionary
 */
interface HazardPattern {
  id: string;
  hazard: string;
  category: 'structural' | 'environmental' | 'medical' | 'electrical' | 'access';
  severity: 'critical' | 'high' | 'medium';
  regex: RegExp;
}

const HAZARD_PATTERNS: HazardPattern[] = [
  {
    id: 'haz_flood_rising',
    hazard: 'Rapidly Rising Floodwater',
    category: 'environmental',
    severity: 'critical',
    regex: /\b(water rising|rising water|water entering|submerged|flooded|waist deep|neck deep|chest deep|flood level)\b/i,
  },
  {
    id: 'haz_trapped_debris',
    hazard: 'Physical Entrapment Under Debris',
    category: 'structural',
    severity: 'critical',
    regex: /\b(trapped|stuck|pinned|debris|rubble|blocked exit|cannot get out|cannot escape|door jammed|collapsed)\b/i,
  },
  {
    id: 'haz_electrical_risk',
    hazard: 'Submerged Electrical Shock / Spark Hazard',
    category: 'electrical',
    severity: 'critical',
    regex: /\b(wire|wiring|spark|sparking|transformer|electric|power line|shock|current in water)\b/i,
  },
  {
    id: 'haz_acute_medical',
    hazard: 'Acute Medical Distress / Prescription Urgency',
    category: 'medical',
    severity: 'critical',
    regex: /\b(bleeding|unconscious|breathing|diabetic|insulin|heart|cardiac|oxygen|pregnant|labor|fracture)\b/i,
  },
  {
    id: 'haz_fire_smoke',
    hazard: 'Active Fire or Dense Smoke Inhalation',
    category: 'environmental',
    severity: 'critical',
    regex: /\b(fire|flames|smoke|burning|gas leak|cylinder|explosion)\b/i,
  },
  {
    id: 'haz_vulnerable_occupants',
    hazard: 'Presence of High-Vulnerability Individuals',
    category: 'access',
    severity: 'high',
    regex: /\b(baby|infant|elderly|old age|grandmother|grandfather|wheelchair|bedridden|disabled|children|kids)\b/i,
  },
  {
    id: 'haz_rooftop_exposure',
    hazard: 'Roof / Terrace Exposure Without Shelter',
    category: 'environmental',
    severity: 'high',
    regex: /\b(roof|rooftop|terrace|open air|rain|hypothermia|cold|shivering)\b/i,
  },
];

/**
 * Deterministic Urgency Rules definition
 */
const URGENCY_RULES: UrgencyRationaleRule[] = [
  {
    ruleId: 'RULE_FLOOD_RISING_VULNERABLE',
    title: 'Rising Floodwater with High-Vulnerability Demographics',
    description: 'Triggered when rising water is reported alongside infants, elderly, pregnant, or mobility-impaired residents.',
    priorityImplication: 'critical',
    isTriggered: false,
  },
  {
    ruleId: 'RULE_STRUCTURAL_TRAPPED',
    title: 'Physical Structural Entrapment',
    description: 'Triggered when persons are unable to evacuate due to debris, collapsed walls, or blocked exits.',
    priorityImplication: 'critical',
    isTriggered: false,
  },
  {
    ruleId: 'RULE_ELECTRICAL_SURGE',
    title: 'Water-Conducted Electrical Hazard',
    description: 'Triggered when live wires or electrical sparks are reported in the vicinity of floodwater.',
    priorityImplication: 'critical',
    isTriggered: false,
  },
  {
    ruleId: 'RULE_ACUTE_MEDICAL_SHORTAGE',
    title: 'Critical Medical or Life-Sustaining Need',
    description: 'Triggered when severe bleeding, breathing distress, or time-critical medicines (insulin, oxygen) are reported.',
    priorityImplication: 'critical',
    isTriggered: false,
  },
  {
    ruleId: 'RULE_PENDING_TIME_ELAPSED',
    title: 'Prolonged Unacknowledged Pending Status',
    description: 'Triggered when an emergency incident remains unacknowledged for more than 45 minutes.',
    priorityImplication: 'high',
    isTriggered: false,
  },
];

/**
 * Analyzes an IncidentRecord and produces a deterministic AI Incident Review report.
 */
export function generateIncidentReview(
  incident: IncidentRecord,
  optionalImage?: { url?: string; description?: string } | null
): IncidentReviewReport {
  const desc = incident.description || '';
  const now = Date.now();
  const createdTime = new Date(incident.created_at).getTime();
  const ageMinutes = Math.max(0, Math.floor((now - createdTime) / 60000));

  // 1. REPORTED FACTS (Strictly what the citizen or telemetry provided)
  const reportedFacts: string[] = [];
  reportedFacts.push(`Reported Emergency Category: ${incident.emergency_type.toUpperCase()}`);
  reportedFacts.push(`Citizen Incident Description: "${desc.trim() || 'No description provided'}"`);
  
  if (hasValidCoordinates(incident)) {
    const acc = incident.accuracy_meters ? ` (Accuracy: ±${Math.round(incident.accuracy_meters)}m)` : '';
    reportedFacts.push(`Reported Coordinates: ${incident.latitude.toFixed(5)}° N, ${incident.longitude.toFixed(5)}° E${acc}`);
  } else {
    reportedFacts.push('Reported Coordinates: None or numerically invalid');
  }

  if (incident.location_name && incident.location_name.trim()) {
    reportedFacts.push(`Reported Landmark: "${incident.location_name.trim()}"`);
  }

  reportedFacts.push(`Incident Age: ${ageMinutes} minute(s) ago`);
  reportedFacts.push(`Current Operational Status: ${incident.status.toUpperCase()}`);
  reportedFacts.push(`Original Citizen Priority: ${incident.priority.toUpperCase()}`);

  // 2. EXTRACT HAZARDS (Via deterministic pattern matching)
  const extractedHazards: ExtractedHazard[] = [];
  HAZARD_PATTERNS.forEach((p) => {
    const match = desc.match(p.regex);
    if (match) {
      extractedHazards.push({
        id: p.id,
        hazard: p.hazard,
        category: p.category,
        severity: p.severity,
        evidenceText: match[0],
      });
    }
  });

  // 3. URGENCY RATIONALE EVALUATION
  const activeRules: UrgencyRationaleRule[] = [];

  const hasRisingWater = extractedHazards.some((h) => h.id === 'haz_flood_rising');
  const hasVulnerable = extractedHazards.some((h) => h.id === 'haz_vulnerable_occupants');
  const hasTrapped = extractedHazards.some((h) => h.id === 'haz_trapped_debris');
  const hasElectrical = extractedHazards.some((h) => h.id === 'haz_electrical_risk');
  const hasMedical = extractedHazards.some((h) => h.id === 'haz_acute_medical');

  if (hasRisingWater && hasVulnerable) {
    activeRules.push({
      ...URGENCY_RULES[0],
      isTriggered: true,
    });
  }

  if (hasTrapped) {
    activeRules.push({
      ...URGENCY_RULES[1],
      isTriggered: true,
    });
  }

  if (hasElectrical) {
    activeRules.push({
      ...URGENCY_RULES[2],
      isTriggered: true,
    });
  }

  if (hasMedical) {
    activeRules.push({
      ...URGENCY_RULES[3],
      isTriggered: true,
    });
  }

  if (incident.status === 'pending' && ageMinutes >= 45) {
    activeRules.push({
      ...URGENCY_RULES[4],
      isTriggered: true,
    });
  }

  // 4. INFERRED POSSIBILITIES (Heuristics based on combination of reported facts)
  const inferredPossibilities: string[] = [];
  if (hasRisingWater) {
    inferredPossibilities.push('Potential loss of ground-floor egress and hypothermia risk if water immersion exceeds 1 hour.');
  }
  if (hasElectrical && hasRisingWater) {
    inferredPossibilities.push('Heightened danger of waterborne electrocution within immediate 15-meter radius of building wiring.');
  }
  if (hasVulnerable && (incident.emergency_type === 'flood' || incident.emergency_type === 'trapped')) {
    inferredPossibilities.push('Vulnerable occupants may require specialized extraction (carry harness, pediatric rations, or stretcher).');
  }
  if (incident.emergency_type === 'fire') {
    inferredPossibilities.push('Smoke inhalation hazard and carbon monoxide accumulation risk inside enclosed rooms.');
  }
  if (inferredPossibilities.length === 0) {
    inferredPossibilities.push('Standard environmental hazard progression depending on local weather conditions.');
  }

  // 5. MISSING INFORMATION (Crucial unknowns for triage)
  const missingInformation: string[] = [];
  if (!incident.location_name || !incident.location_name.trim()) {
    missingInformation.push('Specific landmark, cross street, or building number is missing.');
  }
  if (!/\b(\d+|one|two|three|four|five|six|family|people|persons)\b/i.test(desc)) {
    missingInformation.push('Exact headcount of individuals requiring rescue is unspecified.');
  }
  if (!isValidCoordinate(incident.latitude, incident.longitude)) {
    missingInformation.push('Precise GPS latitude/longitude coordinates are unavailable.');
  } else if (!incident.accuracy_meters || incident.accuracy_meters > 50) {
    missingInformation.push(`GPS coordinate accuracy is coarse (±${incident.accuracy_meters || 'unknown'}m). Pinpoint location unverified.`);
  }
  if (!/\b(floor|ground|first|second|terrace|roof)\b/i.test(desc)) {
    missingInformation.push('Elevation / floor level within structure is not documented.');
  }

  // 6. SUGGESTED OPERATOR VERIFICATIONS
  const suggestedVerifications: string[] = [
    'Confirm if floodwaters / hazards are continuing to escalate or have stabilized.',
    'Verify if occupants have safe vertical retreat (access to terrace or upper floors).',
    'Attempt callback or SMS verification to confirm exact headcount and medical needs.',
  ];
  if (hasElectrical) {
    suggestedVerifications.push('Instruct occupants NOT to touch standing water until local electrical main / grid is isolated.');
  }
  if (hasTrapped) {
    suggestedVerifications.push('Confirm structural stability and identify any secondary collapse hazards.');
  }

  // 7. RECOMMENDED COORDINATION STEPS
  const recommendedCoordinationSteps: string[] = [
    'Acknowledge incident in triage panel to log operator ownership.',
  ];
  if (incident.emergency_type === 'flood' || hasRisingWater) {
    recommendedCoordinationSteps.push('Stage shallow-draft motorized inflatable rescue boat (IRB) or NDRF raft.');
    recommendedCoordinationSteps.push('Map nearest elevated verified relief camp with dry landing zone.');
  } else if (incident.emergency_type === 'building_collapse' || hasTrapped) {
    recommendedCoordinationSteps.push('Alert structural collapse search-and-rescue team with hydraulic cutters.');
  } else if (incident.emergency_type === 'medical' || hasMedical) {
    recommendedCoordinationSteps.push('Coordinate with 108 trauma ambulance for rendezvous at closest dry intersection.');
  } else {
    recommendedCoordinationSteps.push('Maintain active watch on citizen live location updates.');
  }

  // 8. OPTIONAL IMAGE DECISION SUPPORT
  let imageDecisionSupport: ImageDecisionSupport | null = null;
  if (optionalImage && optionalImage.url) {
    imageDecisionSupport = {
      hasImage: true,
      imageUrl: optionalImage.url,
      observationSummary: optionalImage.description || 'Aerial / bystander photo attached. Shows flooded surroundings with partial structural visibility.',
      potentialObstacles: [
        'Visible debris in water corridor',
        'Overhead electrical cables or tree branches hindering boat/drone approach',
      ],
      survivabilityAssessmentDisclaimer:
        'IMAGE SAFETY NOTICE: Model imagery review is strictly preliminary decision support. It cannot verify injury severity or survivability. Visual absence of survivors does NOT indicate an area is clear.',
      isMedicalDiagnosis: false,
    };
  }

  // 9. SUMMARY GENERATION
  const hazardSummary = extractedHazards.length > 0
    ? `Identified ${extractedHazards.length} high-risk factor(s): ${extractedHazards.map((h) => h.hazard).join('; ')}.`
    : 'No acute life-threatening hazard keywords detected in text description.';

  const summary = `AI Incident Review (${incident.emergency_type.toUpperCase()} / Priority: ${incident.priority.toUpperCase()}): ${hazardSummary} ${missingInformation.length} key operational detail(s) require operator verification.`;

  // 10. PRESERVE ORIGINAL PRIORITY (Never drop priority because of missing data)
  let suggestedPriority: IncidentPriority | undefined = undefined;
  if (activeRules.some((r) => r.priorityImplication === 'critical') && incident.priority !== 'critical') {
    suggestedPriority = 'critical';
  }

  return {
    incidentId: incident.id,
    sosId: incident.sos_id,
    generatedAt: new Date().toISOString(),
    summary,
    reportedFacts,
    inferredPossibilities,
    missingInformation,
    extractedHazards,
    urgencyRationale: activeRules,
    originalPriorityPreserved: incident.priority,
    suggestedPriorityReview: suggestedPriority,
    suggestedVerifications,
    recommendedCoordinationSteps,
    imageDecisionSupport,
    safetyNotice: MANDATORY_SAFETY_DISCLAIMER,
    isDecisionSupportOnly: true,
  };
}
